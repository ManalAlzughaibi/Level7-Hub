const app = document.querySelector("#app");

function searchable(c) {
    return [
        c.code,
        c.name,
        c.en,
        ...c.resources.flat(),
        ...c.practice.flat(),
        ...c.books.flat()
    ].join(" ").toLowerCase();
}


// ====================================
// HOME PAGE
// ====================================

function home() {

    document.title = "دليلك للمستوى السابع";

    app.innerHTML = `
        <section class="hero">

            <div class="kicker">
                LEVEL 07 / ONE PLACE
            </div>

            <h1>
                دليلك <em>للمستوى السابع</em>
            </h1>

            <p>
                مواد المستوى السابع في مكان واحد.
            </p>

            <div class="search">
                <span>⌕</span>

                <input
                    id="search"
                    type="text"
                    placeholder="ابحث باسم المادة أو رمزها أو أحد المصادر..."
                >
            </div>

        </section>

        <section class="titlebar">

            <div>
                <small>COURSES</small>
                <h2>مواد المستوى السابع</h2>
            </div>

            <span id="resultCount"></span>

        </section>

        <div id="cards" class="cards"></div>
    `;

    const cards = document.querySelector("#cards");
    const q = document.querySelector("#search");
    const rc = document.querySelector("#resultCount");

    function draw(list) {

        rc.textContent = `${list.length} مواد`;

        cards.innerHTML = list.map(c => `
            <a class="course-card" href="#course/${c.id}">

                <span class="go">↗</span>

                <div class="code">
                    ${c.code}
                </div>

                <h3>${c.name}</h3>

                <p>${c.en}</p>

                <span class="stats"></span>

                <span class="water">
                    ${c.code}
                </span>

            </a>
        `).join("");
    }

    draw(COURSES);

    q.oninput = () => {

        const s = q.value.trim().toLowerCase();

        draw(
            COURSES.filter(c => searchable(c).includes(s))
        );
    };
}


